"""Safe application restore operations; no host or container-engine handles."""

from typing import Protocol


class RestoreRuntime(Protocol):
    """Owning adapter must acknowledge landing and every required service generation."""

    def describe(self) -> dict: ...
    def enter(self) -> None: ...
    def leave(self) -> None: ...
    def prepare(self, vehicle_ids: tuple[str, ...]) -> None: ...
    def state(self, vehicle_id: str) -> dict: ...
    def land(self, vehicle_id: str) -> dict: ...
    def restart(self, vehicle_ids: tuple[str, ...]) -> dict: ...
    def defaults(self) -> dict: ...
